export function assertDashboardMessagesComplete() {
  const keys = Object.keys(dashboardMessages.tr) as DashboardMessageKey[];
  for (const language of SUPPORTED_LANGUAGES) {
    const missing = keys.filter((key) => !dashboardMessages[language.code][key]);
    if (missing.length > 0) {
      throw new Error(`Missing dashboard messages for ${language.code}: ${missing.join(", ")}`);
    }
  }
}
